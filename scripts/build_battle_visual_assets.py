"""Bundle replaceable artwork/font into a Python resource for the bounded release pack."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import textwrap
import zipfile

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'assets/battle_visuals/sources.json'
OUTPUT = ROOT / 'bot/battle_visual_assets.py'


def build(check=False):
    sources = json.loads(MANIFEST.read_text(encoding='utf-8'))
    hashes = {'assets/battle_visuals/sources.json': hashlib.sha256(MANIFEST.read_bytes()).hexdigest()}
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, 'w', zipfile.ZIP_DEFLATED) as archive:
        for key, relative in sorted(sources.items()):
            path = (ROOT / relative).resolve()
            if ROOT not in path.parents:
                raise ValueError('asset must be inside repository')
            raw = path.read_bytes()
            hashes[relative] = hashlib.sha256(raw).hexdigest()
            if key.startswith(('arena/', 'deck/', 'shop/')):
                with Image.open(io.BytesIO(raw)) as original:
                    image = ImageOps.exif_transpose(original).convert('RGB')
                    image.thumbnail((1200, 900), Image.Resampling.LANCZOS)
                    encoded = io.BytesIO()
                    image.save(encoded, 'JPEG', quality=86, optimize=True)
                    raw = encoded.getvalue()
            info = zipfile.ZipInfo(key, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, raw)
    if check:
        import sys
        sys.path.insert(0, str(ROOT))
        from bot.battle_visual_assets import SOURCE_HASHES
        if hashes != SOURCE_HASHES:
            raise ValueError('artwork changed: run python scripts/build_battle_visual_assets.py')
        return
    encoded = '\n'.join('    ' + repr(line) for line in textwrap.wrap(base64.b64encode(stream.getvalue()).decode('ascii'), 100))
    output = ('"""Generated by scripts/build_battle_visual_assets.py; edit the source images instead.\n'
              'Includes Vazirmatn font and its SIL Open Font License in the resource archive.\n"""\n'
              'import base64\nfrom functools import lru_cache\nfrom io import BytesIO\nimport zipfile\n\n'
              'SOURCE_HASHES = ' + repr(hashes) + '\n\n_DATA = (\n' + encoded + '\n)\n\n'
              '@lru_cache(maxsize=1)\ndef resources():\n'
              '    with zipfile.ZipFile(BytesIO(base64.b64decode(_DATA))) as archive:\n'
              '        return {name: archive.read(name) for name in archive.namelist()}\n')
    with OUTPUT.open('w', encoding='utf-8', newline='\n') as destination:
        destination.write(output)
    print('Bundled', len(sources), 'resources;', OUTPUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
