def mode_guide(bot, mode, user_id):
    allowed, reason = bot.modes.mode_access.check(user_id, mode)
    from systems.progression_config import enabled, config_in
    import sqlite3
    from contextlib import closing
    reward = ''
    if enabled(bot.db):
        with closing(sqlite3.connect(bot.db.db_path)) as conn:
            _, config = config_in(conn)
        if mode in ('quick', 'deck'):
            rule = config['match'][mode]
            reward = (f"\n\n🎁 پاداش فعلی رقابتی: برد {rule['win']} XP و {rule['score']} Score؛ "
                      f"مساوی {rule['tie']} XP؛ باخت {rule['loss']} XP و کسر {rule['loss_hearts']} قلب. "
                      'امتیاز Score برای برد است؛ انصراف و اتمام مهلت طبق نتیجهٔ معتبر بازی تسویه می‌شوند.')
        else:
            minimum = config['easy']['min_players']
            lines = [f'\n\n🎁 پاداش فعلی Easy؛ حداقل {minimum} بازیکن با مشارکت معتبر:']
            for rounds, rule in config['easy']['rounds'].items():
                amounts = ' / '.join(str(amount) for amount in rule['xp'])
                lines.append(f"{rounds} راند: XP رتبه‌ها به‌ترتیب {amounts}؛ رتبهٔ اول {rule['score']} Score.")
            if '1' not in config['easy']['rounds']:
                lines.append('بازی یک‌راندی XP و Score ندارد.')
            reward = '\n'.join(lines)
    return GUIDES[mode] + reward + ('\n\n🔒 وضعیت دسترسی تو: ' + reason + '\nبا بازی‌های مجاز و مأموریت‌ها XP بگیر و بعد دوباره امتحان کن.' if not allowed else '')
